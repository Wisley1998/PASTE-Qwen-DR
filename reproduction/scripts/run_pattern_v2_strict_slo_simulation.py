#!/usr/bin/env python3
"""Run the Qwen all-Visit Pattern V2 policy without a tool-timing oracle.

This is a deterministic CPU sensitivity experiment, not the primary live-LLM
result.  The policy is driven through its online API after each completed tool.
Physical tool service is generated by a policy-independent hashed uniform SLO
clock (search/scholar 1--3 seconds; each Visit URL 2--8 seconds); recorded tool
timestamps and ``timing_correction`` fields are never read.  Recorded 0.42x LLM
durations are used only as an environment-side proxy for LLM service and are
not supplied to candidate ranking, admission, or preemption.
"""

